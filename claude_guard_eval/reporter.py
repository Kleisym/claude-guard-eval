"""
Multi-format report generator (Markdown, HTML, JSON) for Claude evaluation and MCP audit results.
"""

import json
from tabulate import tabulate
from .evaluator import EvalResult
from .mcp_scanner import MCPScanResult


class ReportGenerator:
    @staticmethod
    def save_json(eval_result: EvalResult, filepath: str) -> None:
        data = eval_result.model_dump()
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)

    @staticmethod
    def save_markdown(eval_result: EvalResult, filepath: str) -> None:
        table_data = [
            [
                r.test_id,
                r.title,
                r.category,
                "✅ PASS" if r.passed else "❌ FAIL",
                f"{r.latency_ms:.1f}ms",
                r.notes,
            ]
            for r in eval_result.test_results
        ]
        headers = ["ID", "Title", "Category", "Status", "Latency", "Notes"]
        table_md = tabulate(table_data, headers=headers, tablefmt="github")

        content = f"""# 🛡️ Claude Evaluation Audit Report

- **Benchmark Suite**: `{eval_result.benchmark_name}`
- **Target Model**: `{eval_result.model}`
- **Overall Pass Rate**: `{eval_result.pass_rate * 100:.1f}%`
- **Safety Score**: `{eval_result.safety_score:.1f}/100`
- **Tool Accuracy Score**: `{eval_result.tool_accuracy_score:.1f}/100`
- **Average Latency**: `{eval_result.avg_latency_ms:.1f} ms`
- **Total Tokens Consumed**: `{eval_result.total_tokens_used}`
- **Test Summary**: Total `{eval_result.total_tests}` | Passed `{eval_result.passed_tests}` | Failed `{eval_result.failed_tests}`

---

## 📊 Detailed Test Breakdowns

{table_md}

---
*Report generated by [claude-guard-eval](https://github.com/YOUR_USERNAME/claude-guard-eval)*
"""
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)

    @staticmethod
    def save_html(eval_result: EvalResult, filepath: str) -> None:
        test_rows = ""
        for r in eval_result.test_results:
            status_badge = (
                '<span style="background-color: #d1fae5; color: #065f46; padding: 4px 8px; border-radius: 9999px; font-weight: 600;">PASS</span>'
                if r.passed
                else '<span style="background-color: #fee2e2; color: #991b1b; padding: 4px 8px; border-radius: 9999px; font-weight: 600;">FAIL</span>'
            )
            test_rows += f"""
            <tr style="border-bottom: 1px solid #e5e7eb;">
                <td style="padding: 12px; font-weight: bold;">{r.test_id}</td>
                <td style="padding: 12px;">{r.title}</td>
                <td style="padding: 12px;"><code>{r.category}</code></td>
                <td style="padding: 12px;">{status_badge}</td>
                <td style="padding: 12px;">{r.latency_ms:.1f}ms</td>
                <td style="padding: 12px; font-size: 0.9em; color: #4b5563;">{r.notes}</td>
            </tr>
            """

        html_content = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>Claude Guard Audit Report - {eval_result.benchmark_name}</title>
    <style>
        body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; background-color: #f9fafb; color: #111827; margin: 0; padding: 32px; }}
        .card {{ background: #ffffff; border-radius: 12px; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.1); padding: 24px; margin-bottom: 24px; }}
        .grid {{ display: grid; grid-template-columns: repeat(auto-fit, minmax(200px, 1fr)); gap: 16px; margin-bottom: 24px; }}
        .metric {{ background: #f3f4f6; border-radius: 8px; padding: 16px; text-align: center; }}
        .metric-val {{ font-size: 1.8rem; font-weight: bold; color: #2563eb; margin-top: 4px; }}
        table {{ width: 100%; border-collapse: collapse; text-align: left; }}
        th {{ background-color: #f3f4f6; padding: 12px; font-weight: 600; border-bottom: 2px solid #e5e7eb; }}
    </style>
</head>
<body>
    <div style="max-width: 1000px; margin: 0 auto;">
        <div class="card">
            <h1 style="margin-top: 0;">🛡️ Claude Guard Evaluation Report</h1>
            <p style="color: #6b7280;">Benchmark: <strong>{eval_result.benchmark_name}</strong> | Model: <strong>{eval_result.model}</strong></p>
            
            <div class="grid">
                <div class="metric">
                    <div style="font-size: 0.85rem; color: #6b7280;">PASS RATE</div>
                    <div class="metric-val">{eval_result.pass_rate * 100:.1f}%</div>
                </div>
                <div class="metric">
                    <div style="font-size: 0.85rem; color: #6b7280;">SAFETY SCORE</div>
                    <div class="metric-val">{eval_result.safety_score:.1f}/100</div>
                </div>
                <div class="metric">
                    <div style="font-size: 0.85rem; color: #6b7280;">TOOL ACCURACY</div>
                    <div class="metric-val">{eval_result.tool_accuracy_score:.1f}%</div>
                </div>
                <div class="metric">
                    <div style="font-size: 0.85rem; color: #6b7280;">AVG LATENCY</div>
                    <div class="metric-val">{eval_result.avg_latency_ms:.0f}ms</div>
                </div>
            </div>

            <h2>Test Case Breakdown</h2>
            <table>
                <thead>
                    <tr>
                        <th>ID</th>
                        <th>Title</th>
                        <th>Category</th>
                        <th>Status</th>
                        <th>Latency</th>
                        <th>Notes</th>
                    </tr>
                </thead>
                <tbody>
                    {test_rows}
                </tbody>
            </table>
        </div>
    </div>
</body>
</html>
"""
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(html_content)

    @staticmethod
    def save_mcp_markdown(mcp_result: MCPScanResult, filepath: str) -> None:
        table_data = [
            [
                issue.severity,
                issue.tool_name,
                issue.category,
                issue.description,
                issue.recommendation,
            ]
            for issue in mcp_result.issues
        ]
        headers = ["Severity", "Tool Name", "Category", "Description", "Recommendation"]
        table_md = tabulate(table_data, headers=headers, tablefmt="github")

        content = f"""# 🔍 Model Context Protocol (MCP) Audit Report

- **Target Server Command**: `{mcp_result.server_target}`
- **Tools Audited**: `{mcp_result.tools_scanned}`
- **Security Audit Score**: `{mcp_result.security_score}/100`
- **Audit Verdict**: `{"✅ PASSED" if mcp_result.passed else "❌ ACTION REQUIRED"}`

## ⚠️ Identified Vulnerabilities & Schema Recommendations

{table_md}

---
*Report generated by [claude-guard-eval](https://github.com/YOUR_USERNAME/claude-guard-eval)*
"""
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)
